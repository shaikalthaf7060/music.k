export async function searchMusicOnline(query) {
  if (!query || !query.trim()) {
    return { query: "", topResult: null, tracks: [], artists: [], playlists: [] };
  }

  let onlineResults = [];

  try {
    const url = `https://itunes.apple.com/search?term=${encodeURIComponent(query.trim())}&entity=song&limit=35`;
    const res = await fetch(url);
    if (res.ok) {
      const data = await res.json();
      if (data.results && data.results.length > 0) {
        onlineResults = data.results
          .filter(item => item.trackName && item.previewUrl)
          .map(item => {
            // High-resolution authentic release artwork
            const highResCover = item.artworkUrl100 
              ? item.artworkUrl100.replace('100x100bb', '600x600bb') 
              : 'https://is1-ssl.mzstatic.com/image/thumb/Music125/v4/9f/13/ca/9f13ca3b-e533-03e0-f19a-f0aaa774581d/196589311191.jpg/600x600bb.jpg';

            return {
              id: `online-${item.trackId}`,
              title: item.trackName,
              artist: item.artistName,
              album: item.collectionName || "Single",
              duration: Math.round((item.trackTimeMillis || 210000) / 1000),
              genre: item.primaryGenreName || "Music",
              year: item.releaseDate ? new Date(item.releaseDate).getFullYear() : 2024,
              plays: "Popular",
              coverUrl: highResCover,
              audioUrl: item.previewUrl
            };
          });
      }
    }
  } catch (err) {
    console.warn("Live search error:", err);
  }

  const topResult = onlineResults.length > 0 ? { type: "track", data: onlineResults[0] } : null;

  return {
    query,
    topResult,
    tracks: onlineResults,
    artists: [],
    playlists: []
  };
}

export async function fetchOnlineLyrics(track) {
  if (track.lyrics && track.lyrics.length > 0) {
    return { trackId: track.id, lyrics: track.lyrics };
  }

  try {
    const url = `https://lrclib.net/api/get?track_name=${encodeURIComponent(track.title)}&artist_name=${encodeURIComponent(track.artist)}`;
    const res = await fetch(url);
    if (res.ok) {
      const data = await res.json();
      if (data.syncedLyrics) {
        const parsed = parseLrcString(data.syncedLyrics);
        if (parsed.length > 0) {
          return { trackId: track.id, lyrics: parsed };
        }
      }
    }
  } catch (e) {}

  const generated = [
    { time: 0, text: `[Now Playing ${track.title} by ${track.artist}]` },
    { time: 8, text: "Streaming pure online audio" },
    { time: 22, text: `Album: ${track.album || 'music.k'}` },
    { time: 45, text: "music.k" }
  ];

  return { trackId: track.id, lyrics: generated };
}

function parseLrcString(lrc) {
  const lines = lrc.split('\n');
  const result = [];
  const regex = /\[(\d{2}):(\d{2})\.?(\d{2,3})?\](.*)/;

  lines.forEach(line => {
    const match = line.match(regex);
    if (match) {
      const min = parseInt(match[1], 10);
      const sec = parseInt(match[2], 10);
      const ms = match[3] ? parseInt(match[3], 10) / (match[3].length === 2 ? 100 : 1000) : 0;
      const totalSec = min * 60 + sec + ms;
      const text = match[4].trim();
      if (text) {
        result.push({ time: Math.floor(totalSec), text });
      }
    }
  });

  return result;
}

